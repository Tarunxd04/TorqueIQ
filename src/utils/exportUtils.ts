import { FLEET_SHIPS } from '../data/shipsData'
import { MOCK_REPORTS } from '../data/analyticsData'

export function exportFleetCsv() {
  const headers = ['Ship Name', 'IMO Number', 'Type', 'Capacity (DWT)', 'Current Load (t)', 'Status', 'Location', 'Efficiency (%)', 'Current Speed (kts)', 'Fuel Level (%)', 'CO2 Intensity (g/t-NM)']
  
  const rows = FLEET_SHIPS.map(ship => [
    `"${ship.name}"`,
    `"${ship.imo}"`,
    `"${ship.type}"`,
    ship.capacity,
    ship.currentLoad,
    `"${ship.status}"`,
    `"${ship.location}"`,
    ship.fuelEfficiency,
    ship.currentSpeed,
    ship.fuelLevel,
    ship.co2Intensity
  ])

  const csvContent = [headers.join(','), ...rows.map(r => r.join(','))].join('\n')
  downloadBlob(csvContent, `TorqueIQ_Fleet_Audit_${new Date().toISOString().split('T')[0]}.csv`, 'text/csv;charset=utf-8;')
}

export function exportReportsCsv() {
  const headers = ['Report ID', 'Title', 'Category', 'Date', 'Generated By', 'Status', 'Summary']
  
  const rows = MOCK_REPORTS.map(rep => [
    `"${rep.id}"`,
    `"${rep.title}"`,
    `"${rep.type}"`,
    `"${rep.date}"`,
    `"${rep.generatedBy}"`,
    `"${rep.status}"`,
    `"${rep.summary.replace(/"/g, '""')}"`
  ])

  const csvContent = [headers.join(','), ...rows.map(r => r.join(','))].join('\n')
  downloadBlob(csvContent, `TorqueIQ_Reports_Export_${new Date().toISOString().split('T')[0]}.csv`, 'text/csv;charset=utf-8;')
}

function downloadBlob(content: string, filename: string, contentType: string) {
  const blob = new Blob([content], { type: contentType })
  const url = URL.createObjectURL(blob)
  const link = document.createElement('a')
  link.setAttribute('href', url)
  link.setAttribute('download', filename)
  document.body.appendChild(link)
  link.click()
  document.body.removeChild(link)
}
